/**
 * User-visible chrome. Speech [LanguageSettings.current] is separate.
 * Missing or blank fields fall back to English so a button is never empty.
 */
data class UiStrings(
    val chooseLanguages: String,
    val chooseLanguagesBody: String,
    val languagesTitle: String,
    val active: String,
    val continueLabel: String,
    val save: String,
    val back: String,
    val defaultHint: String,
    val couldNotSave: String,
    val packsPlaceholderTemplate: String,
    val appLanguageTitle: String,
    val appLanguageBody: String,
    val speechCurrentTitle: String,
    val speechHelp: String,
    val talk: String,
    val alert: String,
    val analysis: String,
    val pairingTitle: String,
    val pairingBodyTemplate: String,
    val pairingYes: String,
    val pairingCancel: String,
    val appTitle: String,
    val languageLineTemplate: String,
    val settings: String,
    val statusPrefix: String,
    val hostWifi: String,
    val hostBt: String,
    val joinWifi: String,
    val joinBt: String,
    val selectPairedDevice: String,
    val connect: String,
    val disconnect: String,
    val waitingToSendTemplate: String,
    val waitingToSendFailedTemplate: String,
    val inboxTitle: String,
    val newDot: String,
    val play: String,
    val playing: String,
    val dismiss: String,
    val speaking: String,
    val waitingChannel: String,
    val channelBusy: String,
    val readyToSpeak: String,
    val notConnectedQueue: String,
    val ptt: String,
    val stop: String,
    val wait: String,
    val busy: String,
    val alertTitle: String,
    val alertReadyHelp: String,
    val alertNeedPair: String,
    val orTypeAlert: String,
    val freeText: String,
    val sending: String,
    val sendTyped: String,
    val alertSent: String,
    val analysisHelp: String,
    val waitingSample: String,
    val shareJson: String,
    val werTestMode: String,
    val connectionFailedTemplate: String,
    val pairingFailedTemplate: String,
    val playbackErrorTemplate: String,
    val queueSendFailedTemplate: String,
    val pleaseSelectDevice: String,
    val errorTemplate: String,
    val noShareApp: String,
    val shareFailed: String,
    val queuedTitle: String,
    val queuedOneFallback: String,
    val queuedManyTemplate: String,
    val queuedChannelName: String,
    val queuedChannelDesc: String,
) {
    fun pairingBody(code: String): String =
        pairingBodyTemplate.replace("{code}", code)

    fun languageLine(endonym: String, englishName: String): String =
        languageLineTemplate.replace("{endonym}", endonym).replace("{english}", englishName)

    fun waitingToSend(pending: Int, failed: Int): String =
        if (failed > 0) {
            waitingToSendFailedTemplate
                .replace("{n}", pending.toString())
                .replace("{failed}", failed.toString())
        } else {
            waitingToSendTemplate.replace("{n}", pending.toString())
        }

    fun inboxLabel(unread: Boolean, endonym: String): String =
        if (unread) "$newDot · $endonym" else endonym

    fun connectionFailed(detail: String?): String =
        connectionFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun pairingFailed(detail: String?): String =
        pairingFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun playbackError(detail: String?): String =
        playbackErrorTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun queueSendFailed(detail: String?): String =
        queueSendFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    /** Names the languages whose weights are missing, in their own script. */
    fun packsPlaceholder(languages: List<String>): String =
        packsPlaceholderTemplate.replace("{languages}", languages.joinToString(", "))

    fun genericError(detail: String?): String =
        errorTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun queuedBody(unreadCount: Int, preview: String): String = when {
        unreadCount <= 0 -> ""
        unreadCount == 1 -> preview.trim().replace('\n', ' ').take(80).ifBlank { queuedOneFallback }
        else -> queuedManyTemplate.replace("{count}", unreadCount.toString())
    }

    fun allValues(): List<Pair<String, String>> = listOf(
        "chooseLanguages" to chooseLanguages,
        "chooseLanguagesBody" to chooseLanguagesBody,
        "languagesTitle" to languagesTitle,
        "active" to active,
        "continueLabel" to continueLabel,
        "save" to save,
        "back" to back,
        "defaultHint" to defaultHint,
        "couldNotSave" to couldNotSave,
        "packsPlaceholderTemplate" to packsPlaceholderTemplate,
        "appLanguageTitle" to appLanguageTitle,
        "appLanguageBody" to appLanguageBody,
        "speechCurrentTitle" to speechCurrentTitle,
        "speechHelp" to speechHelp,
        "talk" to talk,
        "alert" to alert,
        "analysis" to analysis,
        "pairingTitle" to pairingTitle,
        "pairingBodyTemplate" to pairingBodyTemplate,
        "pairingYes" to pairingYes,
        "pairingCancel" to pairingCancel,
        "appTitle" to appTitle,
        "languageLineTemplate" to languageLineTemplate,
        "settings" to settings,
        "statusPrefix" to statusPrefix,
        "hostWifi" to hostWifi,
        "hostBt" to hostBt,
        "joinWifi" to joinWifi,
        "joinBt" to joinBt,
        "selectPairedDevice" to selectPairedDevice,
        "connect" to connect,
        "disconnect" to disconnect,
        "waitingToSendTemplate" to waitingToSendTemplate,
        "waitingToSendFailedTemplate" to waitingToSendFailedTemplate,
        "inboxTitle" to inboxTitle,
        "newDot" to newDot,
        "play" to play,
        "playing" to playing,
        "dismiss" to dismiss,
        "speaking" to speaking,
        "waitingChannel" to waitingChannel,
        "channelBusy" to channelBusy,
        "readyToSpeak" to readyToSpeak,
        "notConnectedQueue" to notConnectedQueue,
        "ptt" to ptt,
        "stop" to stop,
        "wait" to wait,
        "busy" to busy,
        "alertTitle" to alertTitle,
        "alertReadyHelp" to alertReadyHelp,
        "alertNeedPair" to alertNeedPair,
        "orTypeAlert" to orTypeAlert,
        "freeText" to freeText,
        "sending" to sending,
        "sendTyped" to sendTyped,
        "alertSent" to alertSent,
        "analysisHelp" to analysisHelp,
        "waitingSample" to waitingSample,
        "shareJson" to shareJson,
        "werTestMode" to werTestMode,
        "connectionFailedTemplate" to connectionFailedTemplate,
        "pairingFailedTemplate" to pairingFailedTemplate,
        "playbackErrorTemplate" to playbackErrorTemplate,
        "queueSendFailedTemplate" to queueSendFailedTemplate,
        "pleaseSelectDevice" to pleaseSelectDevice,
        "errorTemplate" to errorTemplate,
        "noShareApp" to noShareApp,
        "shareFailed" to shareFailed,
        "queuedTitle" to queuedTitle,
        "queuedOneFallback" to queuedOneFallback,
        "queuedManyTemplate" to queuedManyTemplate,
        "queuedChannelName" to queuedChannelName,
        "queuedChannelDesc" to queuedChannelDesc,
    )

    companion object {
        fun forLanguage(language: Language): UiStrings {
            val raw = CATALOG[language] ?: ENGLISH
            return raw.withEnglishFallback()
        }
    }
}

