        languageLineTemplate.replace("{endonym}", endonym).replace("{english}", englishName)

    fun waitingToSend(pending: Int, failed: Int): String =
        if (failed > 0) {
            waitingToSendFailedTemplate
                .replace("{n}", pending.toString())
                .replace("{failed}", failed.toString())
        } else {
            waitingToSendTemplate.replace("{n}", pending.toString())
        }

    fun inboxLabel(unread: Boolean, endonym: String): String =
        if (unread) "$newDot · $endonym" else endonym

    fun connectionFailed(detail: String?): String =
        connectionFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun pairingFailed(detail: String?): String =
        pairingFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun playbackError(detail: String?): String =
        playbackErrorTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun queueSendFailed(detail: String?): String =
        queueSendFailedTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun genericError(detail: String?): String =
        errorTemplate.replace("{detail}", detail?.takeIf { it.isNotBlank() } ?: "—")

    fun queuedBody(unreadCount: Int, preview: String): String = when {
        unreadCount <= 0 -> ""
        unreadCount == 1 -> preview.trim().replace('\n', ' ').take(80).ifBlank { queuedOneFallback }
        else -> queuedManyTemplate.replace("{count}", unreadCount.toString())
